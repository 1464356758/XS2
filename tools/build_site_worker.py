#!/usr/bin/env python3
"""将实际网页与受限 GitHub 通道打成 Sites 所需的单文件 Worker。"""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def build(root=ROOT, out=None, partner=False):
    root = Path(root).resolve()
    dist = root / "web/dist"
    names = ["reader.html", "reader.js", "reading-state.mjs", "search.mjs", "hub-core.mjs", "core.mjs", "github-transport.mjs", "query-model.mjs", "ui.mjs", "hub.css", "icon.svg"] if partner else [p.name for p in sorted(dist.iterdir()) if p.is_file() and p.suffix in (".html", ".js", ".mjs", ".css", ".svg", ".webmanifest")]
    types = {".html": "text/html", ".js": "text/javascript", ".mjs": "text/javascript", ".css": "text/css", ".svg": "image/svg+xml", ".webmanifest": "application/manifest+json"}
    assets = {}
    for name in names:
        text = (dist / name).read_text()
        if name.endswith(".html"):
            text = text.replace("<head>", '<head><meta name="novel-github-transport" content="relay">', 1)
        assets["/" + name] = [types[Path(name).suffix] + "; charset=utf-8", text]
    if partner:
        assets["/index.html"] = assets["/reader.html"]
    relay = (root / "web/server/github-relay.mjs").read_text()
    source = "// Generated by tools/build_site_worker.py; no novel data or credentials.\n" + relay
    source += "\nconst ASSETS=" + json.dumps(assets, ensure_ascii=False, separators=(",", ":")) + ";\n"
    source += """
export default {async fetch(request){
  const url=new URL(request.url);
  if(url.pathname==='/api/github')return handleGitHubRelay(request,{allowWrites:ALLOW_WRITES});
  if(!['GET','HEAD'].includes(request.method))return new Response('Method not allowed',{status:405});
  const asset=ASSETS[url.pathname==='/'?'/index.html':url.pathname];
  if(!asset)return new Response('Not found',{status:404});
  return new Response(request.method==='HEAD'?null:asset[1],{headers:{
    'Content-Type':asset[0],'Cache-Control':'no-store','X-Content-Type-Options':'nosniff','X-Frame-Options':'DENY','Referrer-Policy':'no-referrer',
    'Permissions-Policy':'camera=(), microphone=(), geolocation=()',
    'Content-Security-Policy':"default-src 'self'; script-src 'self'; style-src 'self'; connect-src 'self' https://api.github.com https://raw.githubusercontent.com; img-src 'self' data:; font-src 'self'; base-uri 'self'; form-action 'self'; frame-ancestors 'none'; object-src 'none'"
  }});
}};
""".replace("ALLOW_WRITES", "false" if partner else "true")
    if out:
        out = Path(out).resolve()
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(source)
    return source


if __name__ == "__main__":
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--out", required=True)
    p.add_argument("--partner", action="store_true")
    args = p.parse_args()
    build(out=args.out, partner=args.partner)
    print(json.dumps({"output": str(Path(args.out).resolve()), "partner": args.partner}))
